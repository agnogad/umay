/*
 * Minimal SQLite surface for the Phase 3 real-C spike.
 *
 * This is deliberately a SUBSET of <sqlite3.h>. It contains only the four
 * declarations the spike calls, and it uses `void*` for every SQLite handle
 * (`sqlite3*`) instead of the real named C struct. That keeps the header inside
 * the current `umay bindgen` subset, which understands integer/pointer types
 * and opaque struct pointers but does NOT need C struct layout support.
 *
 * A full bindgen over the real <sqlite3.h> would additionally need:
 *   - named struct/union/enum layout (explicit size/alignment from clang),
 *     e.g. sqlite3, sqlite3_stmt, sqlite3_context, sqlite3_value;
 *   - function-pointer typedefs for the sqlite3_exec callback and for
 *     sqlite3_create_function / collation / busy handlers;
 *   - integer #define constants (SQLITE_OK, SQLITE_ROW, SQLITE_DONE, ...) and
 *     enum constants;
 *   - variadic functions such as sqlite3_snprintf and sqlite3_mprintf;
 *   - macro-expanded declarations and #include resolution through -I paths.
 * Those constructs are out of scope for this spike; see docs/v2/ffi-spike.md.
 *
 * No hand-written extern wrapper: the .um bindings are generated by
 * `umay bindgen --header sqlite_min.h --out sqlite_gen.um`.
 */
int sqlite3_open(const char *filename, void **db);
int sqlite3_exec(void *db, const char *sql, void *callback, void *arg, char **errmsg);
int sqlite3_close(void *db);
const char *sqlite3_errmsg(void *db);
