/*
 * Minimal SDL3 surface for the Phase 5 first slice.
 *
 * This is deliberately a SUBSET of <SDL3/SDL.h>: only the declarations the app
 * calls. Every SDL struct handle (SDL_Window, SDL_Surface, SDL_Event, SDL_Rect)
 * is reduced to `void*`. `umay bindgen` has no struct/union support by value:
 * a `struct T` can only be an opaque `extern type` behind a pointer, so
 * flattening to `void*` keeps this header inside bindgen's subset without
 * guessing any C layout. The reduction is ABI-safe: an object pointer and
 * `void*` have the same width on every supported target, and SDL3's `bool` is
 * `_Bool`, a one-byte value (same register/stack byte as UMAY's `bool`).
 * `Uint64`/`Uint32` are written as their C spellings so bindgen maps them to
 * `u64`/`u32`; `int` stays `i32`.
 *
 * Real SDL3 3.4.x signatures, and why each reduction is safe:
 *   bool SDL_Init(Uint64 flags)                              -> bool + u64
 *   void SDL_Quit(void)
 *   SDL_Window *SDL_CreateWindow(const char*, int, int, Uint64)
 *                                                           -> void* + u64 flags
 *   void SDL_DestroyWindow(SDL_Window *)
 *   bool SDL_PollEvent(SDL_Event *)
 *   SDL_Surface *SDL_GetWindowSurface(SDL_Window *)
 *   bool SDL_UpdateWindowSurface(SDL_Window *)
 *   bool SDL_FillSurfaceRect(SDL_Surface *, const SDL_Rect *, Uint32)
 *   void SDL_Delay(Uint32)
 *   const char *SDL_GetError(void)
 *   const bool *SDL_GetKeyboardState(int *)                 -> *const bool, numkeys may be NULL
 *   unsigned long long SDL_GetTicks(void)                   -> u64
 *   SDL_Surface *SDL_CreateSurfaceFrom(int, int, Uint32, void *, int)
 *                                                           -> void* + u32 pixel format
 *   void SDL_DestroySurface(SDL_Surface *)
 *   bool SDL_BlitSurface(SDL_Surface *, const SDL_Rect *, SDL_Surface *, const SDL_Rect *)
 *                                                           -> all pointer args, NULL rects allowed
 *
 * SDL_MapRGB is deliberately absent: in SDL3 it needs a
 * SDL_PixelFormatDetails/SDL_Palette struct reached through SDL_GetSurfaceFormat
 * and friends, which the binder cannot express. The app uses a fixed ARGB8888
 * u32 colour constant instead.
 *
 * No hand-written extern wrapper: the .um bindings are generated by
 * `umay bindgen --header sdl_min.h --out sdl_gen.um`.
 */
bool SDL_Init(unsigned long long flags);
void SDL_Quit(void);
void *SDL_CreateWindow(const char *title, int w, int h, unsigned long long flags);
void SDL_DestroyWindow(void *window);
bool SDL_PollEvent(void *event);
void *SDL_GetWindowSurface(void *window);
bool SDL_UpdateWindowSurface(void *window);
bool SDL_FillSurfaceRect(void *dst, const void *rect, unsigned int color);
void SDL_Delay(unsigned int ms);
const char *SDL_GetError(void);
const bool *SDL_GetKeyboardState(int *numkeys);
unsigned long long SDL_GetTicks(void);
void *SDL_CreateSurfaceFrom(int w, int h, unsigned int format, void *pixels, int pitch);
void SDL_DestroySurface(void *surface);
bool SDL_BlitSurface(void *src, const void *srcrect, void *dst, const void *dstrect);
