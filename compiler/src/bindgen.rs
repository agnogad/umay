//! `umay bindgen` — a deliberately narrow C-header reader (Phase 3, first slice).
//!
//! This is NOT a C parser. It reads semicolon-terminated top-level declarations
//! out of header text and maps the tiny subset needed for the first FFI spike
//! into one v2 `extern "C" { ... }` block. Anything it cannot map is skipped
//! with a `// umay-bindgen: skipped ...` comment — never guessed.
//!
//! Deliberate limits (upgrade to libclang when any of these bite — see
//! `docs/v2/ffi-spike.md` §3):
//! - No `#include` resolution, macro expansion, typedef chains, or `-D/-I` flags.
//!   Preprocessor conditionals are not evaluated: declarations inside an
//!   inactive branch (e.g. `#if 0`) are still scanned and may be emitted.
//! - No structs/unions/enums by value; named `struct T` is an opaque `extern
//!   type` and is only valid behind a pointer. No bitfields, packed/aligned
//!   attributes, function pointers, arrays, VLAs, C++ or `_Atomic`.
//! - Widths are assumed LP64: `long`/`unsigned long` -> `i64`/`u64` and a bare
//!   `char` -> `i8`. Win64 `long` is 32-bit and plain `char` signedness is
//!   target-defined; a target-aware emitter needs libclang plus a target triple.
//! - `const` is applied to every pointer level of a declaration, and any
//!   qualifier in the head (`static`, `inline`, ...) is simply dropped.
//! - Variadic functions ARE emitted as a terminal `...`: the v2 grammar at
//!   `docs/v2/specification.md` §5 accepts `variadic ::= ','? '...'` in an
//!   `extern "C"` block (at least one fixed parameter required). Callers must
//!   still obey E0157 — passing a float to such a call is a diagnostic upstream.
//! - Truncated/unbalanced headers never panic; the trailing unterminated
//!   declaration is ignored (it has no `;`).
//!
//! The generated module carries `#![feature(extern_abi)]` because the v2 extern
//! block is gated (`docs/v2/feature-flags.md` §2). It is data for review, not
//! trusted code.

use std::collections::BTreeSet;

#[derive(Clone)]
struct Segment {
    text: String,
    line: usize,
}

#[derive(Clone, PartialEq, Eq)]
enum Base {
    Void,
    Primitive(&'static str),
    /// An opaque C handle; emitted as `type Name;` inside the extern block.
    Named(String),
}

struct ParsedType {
    base: Base,
    /// Number of `*` in the declaration.
    ptr: usize,
    /// `const` anywhere in the declaration; applied to every pointer level.
    is_const: bool,
}

impl ParsedType {
    fn umay(&self) -> String {
        let mut ty = match &self.base {
            Base::Void => "u8".to_string(), // void* -> *mut u8 / *const u8
            Base::Primitive(p) => (*p).to_string(),
            Base::Named(name) => name.clone(),
        };
        for _ in 0..self.ptr {
            ty = if self.is_const {
                format!("*const {ty}")
            } else {
                format!("*mut {ty}")
            };
        }
        ty
    }

    fn is_void(&self) -> bool {
        self.base == Base::Void && self.ptr == 0
    }
}

/// Generate one UMAY module from header text.
pub fn generate(header_text: &str, header_name: &str) -> String {
    let cleaned = clean_header(header_text);
    let segments = split_declarations(&cleaned);
    let mut opaque: BTreeSet<String> = BTreeSet::new();
    let mut entries: Vec<String> = Vec::new();

    for seg in &segments {
        match parse_segment(seg, &mut opaque) {
            Ok(line) => entries.push(line),
            Err(reason) => entries.push(format!(
                    "    // umay-bindgen: skipped (line {}): {}: `{}`",
                    seg.line,
                    reason,
                    one_line(&seg.text)
                )),
        }
    }

    let mut module = format!(
        "// Generated by `umay bindgen` from `{header_name}`. Do not edit by hand.\n"
    );
    module.push_str("// Deliberate limits: see the note at the top of compiler/src/bindgen.rs.\n");
    module.push_str("#![feature(extern_abi)]\n\n");
    module.push_str("extern \"C\" {\n");
    for entry in entries {
        module.push_str(&entry);
        module.push('\n');
    }
    for name in opaque {
        module.push_str(&format!("    type {name};\n"));
    }
    module.push_str("}\n");

    module
}

// ---- text preparation ------------------------------------------------------

/// Drop comments and preprocessor lines; blank out string/char literals so a
/// `//` or `;` inside one cannot confuse the declaration scanner. Newlines are
/// preserved so skipped-declaration comments can name a source line.
fn clean_header(input: &str) -> String {
    let chars: Vec<char> = input.chars().collect();
    let mut out = String::with_capacity(input.len());
    let mut i = 0usize;
    while i < chars.len() {
        match chars[i] {
            '/' if i + 1 < chars.len() && chars[i + 1] == '/' => {
                while i < chars.len() && chars[i] != '\n' {
                    i += 1;
                }
            }
            '/' if i + 1 < chars.len() && chars[i + 1] == '*' => {
                i += 2;
                while i + 1 < chars.len() && !(chars[i] == '*' && chars[i + 1] == '/') {
                    blank(&mut out, chars[i]);
                    i += 1;
                }
                i = (i + 2).min(chars.len());
                out.push(' ');
            }
            '"' | '\'' => {
                let quote = chars[i];
                i += 1;
                out.push(' ');
                while i < chars.len() {
                    if chars[i] == '\\' {
                        if i + 1 < chars.len() && chars[i + 1] == '\n' {
                            out.push('\n');
                        } else {
                            out.push(' ');
                        }
                        i = (i + 2).min(chars.len());
                    } else if chars[i] == quote {
                        i += 1;
                        break;
                    } else {
                        blank(&mut out, chars[i]);
                        i += 1;
                    }
                }
            }
            c => {
                out.push(c);
                i += 1;
            }
        }
    }
    strip_preprocessor(&out)
}

fn blank(out: &mut String, c: char) {
    out.push(if c == '\n' { '\n' } else { ' ' });
}

fn strip_preprocessor(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut continuing = false;
    for line in text.split('\n') {
        let directive = continuing || line.trim_start().starts_with('#');
        continuing = directive && line.trim_end().ends_with('\\');
        if !directive {
            out.push_str(line);
        }
        // Keep the line break for every line, directive or not, so source line
        // numbers in the emitted comments stay true.
        out.push('\n');
    }
    out
}

/// Split into top-level `;`-terminated declarations. Braces (struct/enum/function
/// bodies) suppress the semicolons inside them. A trailing fragment with no `;`
/// is a truncated declaration and is ignored.
fn split_declarations(text: &str) -> Vec<Segment> {
    let chars: Vec<char> = text.chars().collect();
    let mut segments = Vec::new();
    let mut start = 0usize;
    let mut start_line = 1usize;
    let mut line = 1usize;
    let mut brace_depth = 0i32;
    for (i, &c) in chars.iter().enumerate() {
        match c {
            '{' => brace_depth += 1,
            '}' => brace_depth = (brace_depth - 1).max(0),
            ';' if brace_depth == 0 => {
                let raw: String = chars[start..i].iter().collect();
                let leading_newlines = raw.chars().take_while(|c| c.is_whitespace()).filter(|c| *c == '\n').count();
                segments.push(Segment {
                    text: raw.trim().to_string(),
                    line: start_line + leading_newlines,
                });
                start = i + 1;
                start_line = line;
            }
            '\n' => line += 1,
            _ => {}
        }
    }
    segments
}

fn one_line(text: &str) -> String {
    let flat: String = text.chars().map(|c| if c.is_whitespace() { ' ' } else { c }).collect();
    let flat = flat.trim();
    if flat.chars().count() <= 80 {
        flat.to_string()
    } else {
        let short: String = flat.chars().take(77).collect();
        format!("{short}...")
    }
}

// ---- declaration parsing ---------------------------------------------------

/// Split on whitespace and around the punctuation we care about. `...` stays
/// one token; identifiers and fixed-width typedef names stay intact.
fn words(text: &str) -> Vec<String> {
    let mut spaced = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '(' | ')' | ',' | '*' => {
                spaced.push(' ');
                spaced.push(c);
                spaced.push(' ');
            }
            _ => spaced.push(c),
        }
    }
    spaced.split_whitespace().map(str::to_string).collect()
}

fn is_ident(s: &str) -> bool {
    let mut chars = s.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' => {}
        _ => return false,
    }
    chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

fn matching_paren(chars: &[char], open: usize) -> Option<usize> {
    let mut depth = 0i32;
    for (i, &c) in chars.iter().enumerate().skip(open) {
        match c {
            '(' => depth += 1,
            ')' => {
                depth -= 1;
                if depth == 0 {
                    return Some(i);
                }
            }
            _ => {}
        }
    }
    None
}

fn split_params(text: &str) -> Result<Vec<String>, String> {
    let chars: Vec<char> = text.chars().collect();
    let mut parts = Vec::new();
    let mut start = 0usize;
    let mut depth = 0i32;
    for (i, &c) in chars.iter().enumerate() {
        match c {
            '(' | '[' | '{' => depth += 1,
            ')' | ']' | '}' => depth -= 1,
            ',' if depth == 0 => {
                parts.push(chars[start..i].iter().collect::<String>().trim().to_string());
                start = i + 1;
            }
            _ => {}
        }
        if depth != 0 {
            return Err("function-pointer or nested parameter types are not bound".into());
        }
    }
    parts.push(chars[start..].iter().collect::<String>().trim().to_string());
    Ok(parts)
}

/// Parse one `;`-stripped declaration into an emitted extern item, or a reason
/// it was skipped.
fn parse_segment(seg: &Segment, opaque: &mut BTreeSet<String>) -> Result<String, String> {
    let text = seg.text.trim();
    if text.is_empty() {
        return Err("empty declaration".into());
    }
    if text.contains('{') || text.contains('}') {
        return Err("aggregate or function definition (bodies are not bound)".into());
    }
    let first = words(text).first().cloned().unwrap_or_default();
    if first == "typedef" {
        return Err("typedef (only the fixed-width typedef NAMES are recognised)".into());
    }
    if text.contains('=') {
        return Err("variable declaration with an initializer".into());
    }

    // Work in char indices throughout so non-ASCII text cannot shift a slice.
    let chars: Vec<char> = text.chars().collect();
    let open = chars.iter().position(|&c| c == '(').ok_or_else(|| "not a function declaration".to_string())?;
    let head: String = chars[..open].iter().collect();
    if head.contains(')') {
        return Err("unbalanced declaration".into());
    }
    let close = matching_paren(&chars, open).ok_or_else(|| "unbalanced parameter list".to_string())?;
    let tail: String = chars[close + 1..].iter().collect();
    if !tail.trim().is_empty() {
        return Err("attributes or function-pointer return type after `)` are not bound".into());
    }

    // Head: return type followed by the function name.
    let mut head_words = words(&head);
    let name = head_words.pop().ok_or_else(|| "missing function name".to_string())?;
    if !is_ident(&name) {
        return Err(format!("invalid function name `{name}`"));
    }
    // Only storage-class / linkage words are dropped from the head. Qualifiers
    // such as `const` belong to the type and are handled by `parse_type`.
    let ignored = [
        "extern", "static", "inline", "__inline", "__inline__", "register", "auto",
        "_Noreturn",
    ];
    let head_tokens: Vec<String> =
        head_words.into_iter().filter(|t| !ignored.contains(&t.as_str())).collect();
    let return_type = parse_type(&head_tokens, opaque)?;

    // Parameters.
    let param_text: String = chars[open + 1..close].iter().collect();
    let raw_params = split_params(&param_text)?;
    let mut parts: Vec<String> = Vec::new();
    let mut variadic = false;
    for (i, raw) in raw_params.iter().enumerate() {
        if raw == "..." {
            if i + 1 != raw_params.len() {
                return Err("`...` must be the last parameter".into());
            }
            variadic = true;
            continue;
        }
        if raw.is_empty() {
            return Err("empty parameter".into());
        }
        let (param_name, ptype) = parse_param(raw, opaque)?;
        if ptype.is_void() {
            if raw_params.len() == 1 {
                // C's `f(void)` is UMAY's `f()`.
                continue;
            }
            return Err("`void` parameter alongside other parameters".into());
        }
        let param_name = param_name.unwrap_or_else(|| format!("arg{i}"));
        parts.push(format!("{param_name}: {}", ptype.umay()));
    }
    if variadic && parts.is_empty() {
        return Err("a variadic function needs at least one fixed parameter".into());
    }
    if variadic {
        parts.push("...".to_string());
    }

    let ret = if return_type.is_void() {
        String::new()
    } else {
        format!(" -> {}", return_type.umay())
    };
    Ok(format!("    fn {name}({}){ret};", parts.join(", ")))
}

/// Split a C parameter into an optional name and its type.
fn parse_param(raw: &str, opaque: &mut BTreeSet<String>) -> Result<(Option<String>, ParsedType), String> {
    let mut tokens = words(raw);
    let mut trailing_stars = 0usize;
    while tokens.last().map(String::as_str) == Some("*") {
        tokens.pop();
        trailing_stars += 1;
    }
    // A trailing identifier that leaves a parseable type in front of it is a
    // parameter name; otherwise the parameter is unnamed and gets `argN`.
    if let Some(candidate) = tokens.last().cloned() {
        if is_ident(&candidate) && tokens.len() >= 2 {
            let rest = &tokens[..tokens.len() - 1];
            let mut with_stars = rest.to_vec();
            for _ in 0..trailing_stars {
                with_stars.push("*".into());
            }
            if let Ok(parsed) = parse_type(&with_stars, opaque) {
                return Ok((Some(candidate), parsed));
            }
        }
    }
    let mut all = tokens;
    for _ in 0..trailing_stars {
        all.push("*".into());
    }
    let parsed = parse_type(&all, opaque)?;
    Ok((None, parsed))
}

/// Map C type tokens to a UMAY type. `struct Name` is an opaque extern type and
/// must be behind a pointer; the name is added to `opaque` on success.
fn parse_type(tokens: &[String], opaque: &mut BTreeSet<String>) -> Result<ParsedType, String> {
    let mut ptr = 0usize;
    let mut is_const = false;
    let mut base_tokens: Vec<&str> = Vec::new();
    for token in tokens {
        match token.as_str() {
            "*" => ptr += 1,
            "const" => is_const = true,
            "volatile" | "restrict" | "__restrict" | "__restrict__" => {}
            other => base_tokens.push(other),
        }
    }
    if base_tokens.is_empty() {
        return Err("missing base type".into());
    }

    let base = match base_tokens.as_slice() {
        ["void"] => Base::Void,
        ["char"] | ["signed", "char"] => Base::Primitive("i8"),
        ["unsigned", "char"] => Base::Primitive("u8"),
        ["short"] | ["short", "int"] | ["signed", "short"] | ["signed", "short", "int"] => {
            Base::Primitive("i16")
        }
        ["unsigned", "short"] | ["unsigned", "short", "int"] => Base::Primitive("u16"),
        ["int"] | ["signed"] | ["signed", "int"] => Base::Primitive("i32"),
        ["unsigned"] | ["unsigned", "int"] => Base::Primitive("u32"),
        ["long"] | ["long", "int"] | ["signed", "long"] | ["signed", "long", "int"]
        | ["long", "long"] | ["long", "long", "int"]
        | ["signed", "long", "long"] | ["signed", "long", "long", "int"] => Base::Primitive("i64"),
        ["unsigned", "long"] | ["unsigned", "long", "int"]
        | ["unsigned", "long", "long"] | ["unsigned", "long", "long", "int"] => Base::Primitive("u64"),
        ["float"] => Base::Primitive("f32"),
        ["double"] => Base::Primitive("f64"),
        ["size_t"] | ["uintptr_t"] => Base::Primitive("usize"),
        ["ptrdiff_t"] | ["ssize_t"] | ["intptr_t"] => Base::Primitive("isize"),
        ["_Bool"] | ["bool"] => Base::Primitive("bool"),
        ["long", "double"] => return Err("`long double` is not bound".into()),
        ["struct", name] if is_ident(name) => {
            if ptr == 0 {
                return Err(format!("extern type `{name}` is only valid behind a pointer"));
            }
            opaque.insert((*name).to_string());
            Base::Named((*name).to_string())
        }
        ["struct"] => return Err("anonymous struct is not bound".into()),
        ["union", _] | ["enum", _] => return Err("unions and enums are not bound".into()),
        [single] => {
            if let Some(ty) = fixed_width(single) {
                Base::Primitive(ty)
            } else {
                return Err(format!("unsupported type `{single}`"));
            }
        }
        _ => return Err(format!("unsupported type `{}`", base_tokens.join(" "))),
    };
    Ok(ParsedType { base, ptr, is_const })
}

fn fixed_width(name: &str) -> Option<&'static str> {
    let (digits, signed) = if let Some(rest) = name.strip_prefix("uint") {
        (rest.strip_suffix("_t")?, false)
    } else {
        (name.strip_prefix("int")?.strip_suffix("_t")?, true)
    };
    Some(match (digits, signed) {
        ("8", true) => "i8",
        ("8", false) => "u8",
        ("16", true) => "i16",
        ("16", false) => "u16",
        ("32", true) => "i32",
        ("32", false) => "u32",
        ("64", true) => "i64",
        ("64", false) => "u64",
        _ => return None,
    })
}
