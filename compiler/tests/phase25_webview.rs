//! Phase 25/26: a real Linux webview shell spike (WebKitGTK 4.1 + GTK3).
//!
//! No UMAY FFI declaration is written in this test file or in `main.um`. The
//! only source of FFI declarations is `umay bindgen` output from
//! `examples/v2/webview_gtk/gtk_min.h`, spliced together with `stdlib/ipc.um`
//! and the app body into one crate-root file. The runtime test drives a real
//! X server (`Xvfb`) and the real WebKitGTK libraries; it skips, not fails,
//! when the toolchain, pkg-config entry or Xvfb is unavailable.
//!
//! The GTK calls need no signal callbacks: `gtk_init(NULL, NULL)`, a bounded
//! `gtk_events_pending`/`gtk_main_iteration` pump and `gtk_widget_destroy` are
//! all callback-free, so this is a genuine run-and-assert-stdout test rather
//! than a compile/link-only fallback.

use std::path::{Path, PathBuf};
use std::process::{Child, Command, Output, Stdio};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::thread;
use std::time::{Duration, Instant};

use umayc::target::Target;

static NEXT_DIR: AtomicUsize = AtomicUsize::new(0);
static NEXT_DISPLAY: AtomicUsize = AtomicUsize::new(0);

/// Header path as written in the checked-in binding's "Generated by" line.
const HEADER_REL: &str = "examples/v2/webview_gtk/gtk_min.h";
/// Built from pieces so this test file itself contains no hand-written block.
const FFI_BLOCK: &str = concat!("extern", " \"C\"");

/// The nine declarations bindgen must render from the minimal header.
const EXPECTED_FNS: [&str; 9] = [
    "fn gtk_init(argc: *mut i32, argv: *mut *mut *mut i8);",
    "fn gtk_window_new(window_type: i32) -> *mut u8;",
    "fn webkit_web_view_new() -> *mut u8;",
    "fn gtk_container_add(container: *mut u8, widget: *mut u8);",
    "fn webkit_web_view_load_uri(webview: *mut u8, uri: *const i8);",
    "fn gtk_widget_show_all(widget: *mut u8);",
    "fn gtk_events_pending() -> i32;",
    "fn gtk_main_iteration() -> i32;",
    "fn gtk_widget_destroy(widget: *mut u8);",
];

/// The exact `pkg-config --libs webkit2gtk-4.1` output this spike hardcodes.
const WEBKIT_LIBS: [&str; 18] = [
    "-lwebkit2gtk-4.1",
    "-lgtk-3",
    "-lgdk-3",
    "-lpangocairo-1.0",
    "-lcairo-gobject",
    "-lgdk_pixbuf-2.0",
    "-latk-1.0",
    "-lpango-1.0",
    "-lcairo",
    "-lharfbuzz",
    "-lsoup-3.0",
    "-lgio-2.0",
    "-lgmodule-2.0",
    "-pthread",
    "-lz",
    "-ljavascriptcoregtk-4.1",
    "-lgobject-2.0",
    "-lglib-2.0",
];

const EXPECTED_STDOUT: &str = r#"{"id":7,"ok":true,"result":42}"#;

fn umay() -> Command {
    Command::new(env!("CARGO_BIN_EXE_umay"))
}

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("compiler/ sits under the repo root")
        .to_path_buf()
}

fn examples() -> PathBuf {
    repo_root().join("examples/v2/webview_gtk")
}

struct TempDir(PathBuf);

impl TempDir {
    fn new(tag: &str) -> Self {
        let n = NEXT_DIR.fetch_add(1, Ordering::Relaxed);
        let dir = std::env::temp_dir().join(format!(
            "umay-webview-{tag}-{}-{n}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).expect("create temp dir");
        TempDir(dir)
    }

    fn path(&self, name: &str) -> PathBuf {
        self.0.join(name)
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn run(cmd: &mut Command) -> Output {
    cmd.output().expect("run command")
}

fn assert_ok(output: &Output, what: &str) {
    assert!(
        output.status.success(),
        "{what} failed (status {:?}):\nstdout:\n{}\nstderr:\n{}",
        output.status.code(),
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

fn have_tool(name: &str) -> bool {
    Command::new(name)
        .arg("--version")
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .map(|s| s.success())
        .unwrap_or(false)
}

/// Xvfb has no `--version`; a successful `spawn` is the availability check.
fn have_xvfb() -> bool {
    Command::new("Xvfb")
        .arg("-help")
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .map(|mut child| {
            let _ = child.kill();
            let _ = child.wait();
            true
        })
        .unwrap_or(false)
}

fn have_webkit() -> bool {
    have_tool("pkg-config")
        && Command::new("pkg-config")
            .args(["--exists", "webkit2gtk-4.1"])
            .status()
            .map(|s| s.success())
            .unwrap_or(false)
}

/// Collect a child's output, killing it if it outlives `limit`. WebKit spawns
/// helper processes, so a hung event pump must not hang the test suite.
fn run_with_timeout(cmd: &mut Command, limit: Duration) -> Output {
    let mut child = cmd
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("spawn command");
    let start = Instant::now();
    loop {
        match child.try_wait() {
            Ok(Some(_)) => break,
            Ok(None) if start.elapsed() < limit => thread::sleep(Duration::from_millis(50)),
            Ok(None) => {
                let _ = child.kill();
                panic!("command timed out after {limit:?}: {cmd:?}");
            }
            Err(e) => panic!("try_wait failed: {e}"),
        }
    }
    child.wait_with_output().expect("collect command output")
}

/// An Xvfb on a display number unique to this process (and to this test within
/// it). Dropping the guard kills the server even when an assertion panics.
struct XvfbGuard {
    child: Child,
    display: String,
}

impl XvfbGuard {
    fn start() -> Option<Self> {
        let n = NEXT_DISPLAY.fetch_add(1, Ordering::Relaxed);
        let number = 99 + (std::process::id() % 64) as usize + n;
        let display = format!(":{number}");
        let child = Command::new("Xvfb")
            .arg(&display)
            .args(["-screen", "0", "1280x800x24", "-nolisten", "tcp"])
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .spawn()
            .ok()?;
        // Wait for the UNIX socket rather than sleeping a fixed amount: a slow
        // CI machine can take longer to bring the server up.
        let socket = PathBuf::from(format!("/tmp/.X11-unix/X{number}"));
        for _ in 0..100 {
            if socket.exists() {
                return Some(XvfbGuard { child, display });
            }
            thread::sleep(Duration::from_millis(50));
        }
        let mut child = child;
        let _ = child.kill();
        let _ = child.wait();
        None
    }
}

impl Drop for XvfbGuard {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
    }
}

/// Always runs, even where no C toolchain exists: the no-hand-written-FFI rule
/// is a property of the sources, not of the host.
#[test]
fn webview_sources_have_no_hand_written_ffi() {
    let body = std::fs::read_to_string(examples().join("main.um")).expect("read main.um");
    assert!(
        !body.contains("extern"),
        "main.um must contain zero hand-written FFI declarations:\n{body}"
    );
    let test_src = include_str!("phase25_webview.rs");
    assert!(
        !test_src.contains(FFI_BLOCK),
        "the test source must not hand-write an FFI block"
    );
    assert!(
        !test_src.contains(concat!("extern", " fn")),
        "the test source must not hand-write a UMAY FFI declaration"
    );
}

/// Byte-exact reproducibility and `umay check` acceptance of the generated
/// binding. Needs only the compiler binary, which cargo builds for this test.
#[test]
fn generated_binding_is_byte_exact_and_checks() {
    let repo = repo_root();
    let dir = TempDir::new("bindgen");
    let out = dir.path("gtk_gen.um");
    let mut bind = umay();
    bind.current_dir(&repo)
        .args(["bindgen", "--header"])
        .arg(HEADER_REL)
        .args(["--out"])
        .arg(&out);
    assert_ok(&run(&mut bind), "bindgen");
    let generated = std::fs::read_to_string(&out).expect("read generated binding");

    let checked_in = std::fs::read_to_string(examples().join("gtk_gen.um"))
        .expect("read checked-in generated binding");
    assert_eq!(
        generated, checked_in,
        "checked-in gtk_gen.um differs from fresh `umay bindgen` output"
    );
    for needle in EXPECTED_FNS {
        assert!(
            generated.contains(needle),
            "bindgen skipped or mis-rendered `{needle}`:\n{generated}"
        );
    }
    assert!(
        !generated.contains("umay-bindgen: skipped"),
        "bindgen skipped a declaration from the GTK header:\n{generated}"
    );
    assert_ok(&run(umay().arg("check").arg(&out)), "umay check generated binding");
}

/// The linker rule: a GTK or WebKit callee adds the full hardcoded flag list;
/// SQLite and SDL3 keep their original one-flag rules.
#[test]
fn webview_callees_add_the_full_webkit_flag_list() {
    let expected = WEBKIT_LIBS.to_vec();
    assert_eq!(
        Target::system_libraries("    call gtk_init\n    call webkit_web_view_new\n"),
        expected
    );
    assert_eq!(
        Target::system_libraries("    call _gtk_widget_destroy\n    call webkit_web_view_load_uri\n"),
        expected
    );
    assert!(Target::system_libraries("    call umay_println\n").is_empty());
    assert_eq!(
        Target::system_libraries("    call sqlite3_open_v2\n    call SDL_Init\n"),
        vec!["-lsqlite3", "-lSDL3"]
    );
}

/// The real thing: splice, `umay build` (auto-linking through target.rs), then
/// run under Xvfb and assert the exact IPC JSON and a zero exit code.
#[test]
fn webview_shell_runs_under_xvfb() {
    if !have_tool("as") || !have_tool("cc") || !have_webkit() || !have_xvfb() {
        eprintln!("skip webview_shell_runs_under_xvfb: toolchain, WebKitGTK or Xvfb absent");
        return;
    }
    // pkg-config is present; confirm the library flags are non-empty too, so a
    // broken metadata file cannot make the link silently succeed with no GTK.
    let pkg = run(Command::new("pkg-config").args(["--libs", "webkit2gtk-4.1"]));
    assert_ok(&pkg, "pkg-config --libs webkit2gtk-4.1");
    assert!(
        !String::from_utf8_lossy(&pkg.stdout).trim().is_empty(),
        "pkg-config gave no WebKitGTK flags"
    );

    let examples = examples();
    let dir = TempDir::new("run");
    let generated = std::fs::read_to_string(examples.join("gtk_gen.um"))
        .expect("read checked-in generated binding");
    let ipc = std::fs::read_to_string(repo_root().join("stdlib/ipc.um")).expect("read ipc.um");
    let body = std::fs::read_to_string(examples.join("main.um")).expect("read main.um");

    // Byte-exact concatenation: the body contributed no declarations of its own.
    let main = dir.path("main.um");
    std::fs::write(&main, format!("{generated}{ipc}{body}")).expect("write spliced main.um");
    let built_source = std::fs::read_to_string(&main).expect("read spliced main.um");
    assert_eq!(
        built_source.matches(FFI_BLOCK).count(),
        generated.matches(FFI_BLOCK).count(),
        "the built program has FFI declarations that did not come from bindgen"
    );

    let xvfb = match XvfbGuard::start() {
        Some(x) => x,
        None => {
            eprintln!("skip webview_shell_runs_under_xvfb: Xvfb failed to start");
            return;
        }
    };

    let mut build = umay();
    build
        .current_dir(&dir.0)
        .env("DISPLAY", &xvfb.display)
        .args(["build", "main.um"]);
    assert_ok(&run(&mut build), "umay build main.um");
    let exe = dir.path("dist/main");
    assert!(exe.exists(), "umay build produced no executable");

    let mut runner = Command::new(&exe);
    runner
        .current_dir(&dir.0)
        .env("DISPLAY", &xvfb.display)
        .env("WEBKIT_DISABLE_SANDBOX_THIS_IS_DANGEROUS", "1");
    let ran = run_with_timeout(&mut runner, Duration::from_secs(30));
    assert!(
        ran.status.success(),
        "webview program failed (status {:?}):\nstdout:\n{}\nstderr:\n{}",
        ran.status.code(),
        String::from_utf8_lossy(&ran.stdout),
        String::from_utf8_lossy(&ran.stderr)
    );
    assert_eq!(ran.status.code(), Some(0), "webview program exit code");
    assert_eq!(
        String::from_utf8_lossy(&ran.stdout).trim_end(),
        EXPECTED_STDOUT,
        "webview program stdout is not the deterministic IPC reply"
    );
}
