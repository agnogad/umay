//! Phase 18: the real-C spike — bind and use SQLite from `umay bindgen` output.
//!
//! No C declaration is written in this test file or in `main.um`. The only
//! source of FFI declarations is the module `umay bindgen` emits from
//! `examples/v2/sqlite_spike/sqlite_min.h`. Like phase 5 / phase 14, the test
//! skips (rather than fails) when a toolchain piece is missing.
//!
//! The generated module is spliced directly above `main.um` into one crate-root
//! file before building. That is deliberate: a declaration inside `mod`
//! `sqlite_gen;` is private (E1018) and codegen spells it
//! `sqlite_gen::sqlite3_open`, which the assembler rejects. Splicing keeps the
//! generated bytes unchanged and needs no hand-written wrapper. The splice is
//! byte-exact, so every FFI declaration in the built program comes from
//! bindgen.

use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::atomic::{AtomicUsize, Ordering};

static NEXT_DIR: AtomicUsize = AtomicUsize::new(0);

fn umay() -> Command {
    Command::new(env!("CARGO_BIN_EXE_umay"))
}

/// The spike lives beside `compiler/`, at the repository root.
fn spike_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("compiler/ sits under the repo root")
        .join("examples/v2/sqlite_spike")
}

/// Header path as written in the checked-in binding's "Generated by" line.
const HEADER_REL: &str = "examples/v2/sqlite_spike/sqlite_min.h";
/// Built from pieces so this test file itself contains no hand-written block.
const EXTERN_BLOCK: &str = concat!("extern", " \"C\"");

struct TempDir(PathBuf);

impl TempDir {
    fn new(tag: &str) -> Self {
        let n = NEXT_DIR.fetch_add(1, Ordering::Relaxed);
        let dir = std::env::temp_dir().join(format!(
            "umay-sqlite-spike-{tag}-{}-{n}",
            std::process::id()
        ));
        std::fs::create_dir_all(&dir).expect("create temp dir");
        TempDir(dir)
    }

    fn path(&self, name: &str) -> PathBuf {
        self.0.join(name)
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn run(cmd: &mut Command) -> Output {
    cmd.output().expect("run command")
}

fn assert_ok(output: &Output, what: &str) {
    assert!(
        output.status.success(),
        "{what} failed (status {:?}):\nstdout:\n{}\nstderr:\n{}",
        output.status.code(),
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

fn have_tool(name: &str) -> bool {
    Command::new(name)
        .arg("--version")
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status()
        .map(|s| s.success())
        .unwrap_or(false)
}

/// The four declarations the spike needs, exactly as bindgen must render them.
const EXPECTED_FNS: [&str; 4] = [
    "fn sqlite3_open(filename: *const i8, db: *mut *mut u8) -> i32;",
    "fn sqlite3_exec(db: *mut u8, sql: *const i8, callback: *mut u8, arg: *mut u8, errmsg: *mut *mut i8) -> i32;",
    "fn sqlite3_close(db: *mut u8) -> i32;",
    "fn sqlite3_errmsg(db: *mut u8) -> *const i8;",
];

/// Always runs, even where no C toolchain exists: the no-hand-wrapper rule is
/// a property of the sources, not of the host.
#[test]
fn spike_sources_have_no_hand_written_ffi() {
    let spike = spike_dir();
    let body = std::fs::read_to_string(spike.join("main.um")).expect("read main.um");
    assert!(
        !body.contains("extern"),
        "main.um must contain zero hand-written FFI declarations:\n{body}"
    );

    let test_src = include_str!("phase18_sqlite_spike.rs");
    assert!(
        !test_src.contains(EXTERN_BLOCK),
        "the test source must not hand-write an FFI block"
    );
    assert!(
        !test_src.contains(concat!("extern", " fn")),
        "the test source must not hand-write an FFI declaration"
    );
}

#[test]
fn sqlite_spike_runs_generated_bindings() {
    // Skip, don't fail, without a linker, an assembler, pkg-config or SQLite.
    if !have_tool("as") || !have_tool("cc") || !have_tool("pkg-config") {
        eprintln!("skip sqlite_spike_runs_generated_bindings: toolchain missing");
        return;
    }
    let pkg = run(Command::new("pkg-config").args(["--libs", "sqlite3"]));
    if !pkg.status.success() {
        eprintln!(
            "skip sqlite_spike_runs_generated_bindings: sqlite3 not found by pkg-config: {}",
            String::from_utf8_lossy(&pkg.stderr)
        );
        return;
    }
    let libs: Vec<String> = String::from_utf8_lossy(&pkg.stdout)
        .split_whitespace()
        .map(str::to_string)
        .collect();
    assert!(!libs.is_empty(), "pkg-config --libs sqlite3 gave no flags");

    let spike = spike_dir();
    let checked_in = std::fs::read_to_string(spike.join("sqlite_gen.um"))
        .expect("read checked-in generated binding");
    let body = std::fs::read_to_string(spike.join("main.um")).expect("read main.um");

    let dir = TempDir::new("sqlite");
    let out = dir.path("sqlite_gen.um");
    // Run from the repo root so the header name in the generated comment is the
    // same relative spelling used when sqlite_gen.um was checked in.
    let repo = spike.parent().unwrap().parent().unwrap().parent().unwrap();
    let mut bind = umay();
    bind.current_dir(repo)
        .args(["bindgen", "--header"])
        .arg(HEADER_REL)
        .args(["--out"])
        .arg(&out);
    assert_ok(&run(&mut bind), "bindgen");
    let generated = std::fs::read_to_string(&out).expect("read generated binding");

    // The checked-in binding is byte-for-byte what bindgen emits: no hand edit
    // can fake a passing check here.
    assert_eq!(
        generated, checked_in,
        "checked-in sqlite_gen.um differs from fresh `umay bindgen` output"
    );
    for needle in EXPECTED_FNS {
        assert!(
            generated.contains(needle),
            "bindgen skipped or mis-rendered `{needle}`:\n{generated}"
        );
    }
    assert!(
        !generated.contains("umay-bindgen: skipped"),
        "bindgen skipped a declaration from the spike header:\n{generated}"
    );
    assert_ok(&run(umay().arg("check").arg(&out)), "umay check generated binding");

    // Splice the generated bytes above the program body into a crate-root
    // main.um. Byte-exact concatenation is what makes bindgen the only FFI
    // source: the body contributed no declarations of its own.
    let main = dir.path("main.um");
    std::fs::write(&main, format!("{generated}{body}")).expect("write spliced main.um");
    let built_main = std::fs::read_to_string(&main).expect("read spliced main.um");
    assert_eq!(
        built_main.matches(EXTERN_BLOCK).count(),
        generated.matches(EXTERN_BLOCK).count(),
        "the built program has FFI declarations that did not come from bindgen"
    );

    let mut build = umay();
    build
        .current_dir(&dir.0)
        .args(["build", "--emit-object-only"])
        .arg("main.um");
    let built = run(&mut build);
    assert_ok(&built, "umay build --emit-object-only main.um");

    // Use the link command the compiler printed, with pkg-config's -lsqlite3
    // appended: the CI pattern for libraries `umay build` cannot pass -l for.
    let stdout = String::from_utf8_lossy(&built.stdout);
    let link = stdout
        .lines()
        .find_map(|l| l.trim().strip_prefix("link it with: "))
        .unwrap_or_else(|| panic!("no link command printed:\n{stdout}"));
    assert!(
        link.contains("dist/main.o") && link.contains("dist/umay_runtime.o"),
        "the link command must name both objects: {link}"
    );
    let mut cc_args: Vec<String> = link.split_whitespace().skip(1).map(str::to_string).collect();
    cc_args.extend(libs);
    let mut link_cmd = Command::new("cc");
    link_cmd.current_dir(&dir.0).args(&cc_args);
    let linked = run(&mut link_cmd);
    assert_ok(&linked, "link with cc and -lsqlite3");

    let mut runner = Command::new(dir.path("dist/main"));
    runner.current_dir(&dir.0);
    let ran = run(&mut runner);
    assert_ok(&ran, "run the spike");
    // `CREATE TABLE ...; INSERT ...;` through sqlite3_exec returns SQLITE_OK.
    assert_eq!(
        String::from_utf8_lossy(&ran.stdout).trim_end(),
        "0",
        "expected sqlite3_exec status 0 on stdout"
    );
}
