//! Phase 7: the 2D sprite demo driven entirely by `umay bindgen` output.
//!
//! No UMAY FFI declaration is written in this test file or in `p7_sprite.um`.
//! The only source of UMAY FFI declarations is the generated module bindgen
//! emits from `examples/v2/sdl_min.h`. As in `phase20_sdl_smoke.rs`, that module,
//! the pure-UMAY `game_core.um` and the app body are spliced into one crate-root
//! file before building: a declaration inside `mod sdl_gen;` is private (E1018)
//! and codegen spells it `sdl_gen::SDL_Init`, which the assembler rejects.
//! Here the splice is `generated binding + game core + app`.
//!
//! The header binds the real SDL3 3.4.x signatures, so `umay build` sees the
//! `SDL_` callees and links with `-lSDL3` on its own. The test skips (rather
//! than fails) when a toolchain piece or SDL3 is absent. The in-process `sema`
//! check and the no-hand-wrapper rule are host-independent and always run.

use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::atomic::{AtomicUsize, Ordering};

use umayc::diagnostics::Diagnostics;
use umayc::lexer;
use umayc::parser;
use umayc::prelude;
use umayc::sema;
use umayc::source::SourceMap;
use umayc::target::Target;

static NEXT_DIR: AtomicUsize = AtomicUsize::new(0);

fn umay() -> Command {
    Command::new(env!("CARGO_BIN_EXE_umay"))
}

/// The examples live beside `compiler/`, at the repository root.
fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("compiler/ sits under the repo root")
        .to_path_buf()
}

/// Header path as written in the checked-in binding's "Generated by" line.
const HEADER_REL: &str = "examples/v2/sdl_min.h";
/// Built from pieces so this test file itself contains no hand-written block.
const EXTERN_BLOCK: &str = concat!("extern", " \"C\"");

/// The 15 declarations the demo needs, exactly as bindgen must render them:
/// the original 10 plus keyboard state, ticks, surface-from, destroy-surface
/// and blit-surface.
const EXPECTED_FNS: [&str; 15] = [
    "fn SDL_Init(flags: u64) -> bool;",
    "fn SDL_Quit();",
    "fn SDL_CreateWindow(title: *const i8, w: i32, h: i32, flags: u64) -> *mut u8;",
    "fn SDL_DestroyWindow(window: *mut u8);",
    "fn SDL_PollEvent(event: *mut u8) -> bool;",
    "fn SDL_GetWindowSurface(window: *mut u8) -> *mut u8;",
    "fn SDL_UpdateWindowSurface(window: *mut u8) -> bool;",
    "fn SDL_FillSurfaceRect(dst: *mut u8, rect: *const u8, color: u32) -> bool;",
    "fn SDL_Delay(ms: u32);",
    "fn SDL_GetError() -> *const i8;",
    "fn SDL_GetKeyboardState(numkeys: *mut i32) -> *const bool;",
    "fn SDL_GetTicks() -> u64;",
    "fn SDL_CreateSurfaceFrom(w: i32, h: i32, format: u32, pixels: *mut u8, pitch: i32) -> *mut u8;",
    "fn SDL_DestroySurface(surface: *mut u8);",
    "fn SDL_BlitSurface(src: *mut u8, srcrect: *const u8, dst: *mut u8, dstrect: *const u8) -> bool;",
];

struct TempDir(PathBuf);

impl TempDir {
    fn new(tag: &str) -> Self {
        let n = NEXT_DIR.fetch_add(1, Ordering::Relaxed);
        let dir = std::env::temp_dir().join(format!(
            "umay-sprite-smoke-{tag}-{}-{n}",
            std::process::id()
        ));
        std::fs::create_dir_all(&dir).expect("create temp dir");
        TempDir(dir)
    }

    fn path(&self, name: &str) -> PathBuf {
        self.0.join(name)
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn run(cmd: &mut Command) -> std::process::Output {
    cmd.output().expect("run command")
}

fn assert_ok(output: &std::process::Output, what: &str) {
    assert!(
        output.status.success(),
        "{what} failed (status {:?}):\nstdout:\n{}\nstderr:\n{}",
        output.status.code(),
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
}

fn have_tool(name: &str) -> bool {
    Command::new(name)
        .arg("--version")
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status()
        .map(|s| s.success())
        .unwrap_or(false)
}

/// True when the host has SDL3's development files, i.e. a library to link.
fn have_sdl3() -> bool {
    have_tool("pkg-config")
        && Command::new("pkg-config")
            .args(["--exists", "sdl3"])
            .status()
            .map(|s| s.success())
            .unwrap_or(false)
}

/// lex -> parse -> prelude -> `sema::analyze`, mirroring phase20_gui_core.rs.
/// The prelude is injected because the core and app use `alloc`, `Args`,
/// `write_u32`, `byte_len`, `println_i64`, etc., which every spliced program
/// gets for free.
fn analyze(src: &str) -> Diagnostics {
    let mut map = SourceMap::new();
    let file = map.add("<sprite>", src);
    let (tokens, lex_errors) = lexer::tokenize(src, file);
    assert!(lex_errors.is_empty(), "lex errors: {lex_errors:?}\n---\n{src}");
    let parsed = parser::parse(tokens, Vec::new(), file);
    let parse_errors: Vec<_> = parsed
        .diagnostics
        .iter()
        .filter(|d| d.severity.is_fatal())
        .map(|d| format!("{}: {}", d.code, d.message))
        .collect();
    assert!(parse_errors.is_empty(), "parse errors: {parse_errors:?}\n---\n{src}");
    let (program, prelude_diags) =
        prelude::with_prelude(parsed.program, &mut map, Target::LINUX);
    assert!(!prelude_diags.has_errors(), "prelude errors: {prelude_diags:?}");
    let out = sema::analyze(&program, &map);
    if out.diagnostics.has_errors() {
        eprintln!("{}", umayc::render_all(&out.diagnostics, &map, false));
    }
    out.diagnostics
}

/// Always runs, even where no C toolchain exists: the no-hand-wrapper rule and
/// the in-process type check are properties of the sources, not of the host.
#[test]
fn sprite_sources_have_no_hand_written_ffi() {
    let body = std::fs::read_to_string(repo_root().join("examples/v2/p7_sprite.um"))
        .expect("read p7_sprite.um");
    assert!(
        !body.contains("extern"),
        "p7_sprite.um must contain zero hand-written FFI declarations:\n{body}"
    );
    assert!(
        !body.contains("#![feature]") && !body.contains("#![feature("),
        "p7_sprite.um must not carry a feature attribute:\n{body}"
    );
    let test_src = include_str!("phase21_sprite_smoke.rs");
    assert!(
        !test_src.contains(EXTERN_BLOCK),
        "the test source must not hand-write an FFI block"
    );
    assert!(
        !test_src.contains(concat!("extern", " fn")),
        "the test source must not hand-write a UMAY FFI declaration"
    );
}

/// The full spliced program must type-check in-process, independent of a
/// toolchain. This is the same lex -> parse -> prelude -> sema path used by
/// phase2_sema.rs and phase20_gui_core.rs, fed the real three source texts.
#[test]
fn sprite_program_typechecks_in_process() {
    let repo = repo_root();
    let generated = std::fs::read_to_string(repo.join("examples/v2/sdl_gen.um"))
        .expect("read generated binding");
    let core = std::fs::read_to_string(repo.join("examples/v2/game_core.um"))
        .expect("read game_core.um");
    let body = std::fs::read_to_string(repo.join("examples/v2/p7_sprite.um"))
        .expect("read p7_sprite.um");
    let diags = analyze(&format!("{generated}{core}{body}"));
    assert!(!diags.has_errors(), "spliced sprite program does not type-check");
}

#[test]
fn sprite_smoke_runs_generated_bindings() {
    // Skip, don't fail, without an assembler, a linker or SDL3.
    if !have_tool("as") || !have_tool("cc") || !have_sdl3() {
        eprintln!("skip sprite_smoke_runs_generated_bindings: toolchain or SDL3 absent");
        return;
    }

    let repo = repo_root();
    let examples = repo.join("examples/v2");
    let dir = TempDir::new("sprite");

    // Run from the repo root so the header name in the generated comment is
    // the same relative spelling used when sdl_gen.um was checked in.
    let out = dir.path("sdl_gen.um");
    let mut bind = umay();
    bind.current_dir(&repo)
        .args(["bindgen", "--header"])
        .arg(HEADER_REL)
        .args(["--out"])
        .arg(&out);
    assert_ok(&run(&mut bind), "bindgen");
    let generated = std::fs::read_to_string(&out).expect("read generated binding");

    // Byte-exact: no hand edit can fake this check.
    let checked_in = std::fs::read_to_string(examples.join("sdl_gen.um"))
        .expect("read checked-in generated binding");
    assert_eq!(
        generated, checked_in,
        "checked-in sdl_gen.um differs from fresh `umay bindgen` output"
    );
    for needle in EXPECTED_FNS {
        assert!(
            generated.contains(needle),
            "bindgen skipped or mis-rendered `{needle}`:\n{generated}"
        );
    }
    assert!(
        !generated.contains("umay-bindgen: skipped"),
        "bindgen skipped a declaration from the SDL header:\n{generated}"
    );
    assert_ok(&run(umay().arg("check").arg(&out)), "umay check generated binding");

    let core = std::fs::read_to_string(examples.join("game_core.um"))
        .expect("read game_core.um");
    let body = std::fs::read_to_string(examples.join("p7_sprite.um"))
        .expect("read p7_sprite.um");

    // Byte-exact concatenation: the body contributed no declarations of its own.
    let main = dir.path("main.um");
    std::fs::write(&main, format!("{generated}{core}{body}")).expect("write spliced main.um");
    let built_main = std::fs::read_to_string(&main).expect("read spliced main.um");
    assert_eq!(
        built_main.matches(EXTERN_BLOCK).count(),
        generated.matches(EXTERN_BLOCK).count(),
        "the built program has FFI declarations that did not come from bindgen"
    );

    // `umay build` assembles and links with -lSDL3 (detected from the SDL_
    // callees) in one step. No C shim and no manual cc invocation.
    let mut build = umay();
    build.current_dir(&dir.0).args(["build", "main.um"]);
    assert_ok(&run(&mut build), "umay build main.um");
    assert!(dir.path("dist/main").exists(), "umay build produced no executable");

    // --selftest drives a synthetic RIGHT+UP buffer for three steps from
    // (0,8), so stdout is the single deterministic line `SPRITE_OK 3 5`.
    let mut runner = Command::new(dir.path("dist/main"));
    runner
        .current_dir(&dir.0)
        .env("SDL_VIDEODRIVER", "dummy")
        .arg("--selftest");
    let ran = run(&mut runner);
    assert_ok(&ran, "run the sprite smoke program");
    assert_eq!(
        String::from_utf8_lossy(&ran.stdout).trim_end(),
        "SPRITE_OK 3 5",
        "expected the deterministic SPRITE_OK line on stdout"
    );
}
